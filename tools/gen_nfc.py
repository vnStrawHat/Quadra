"""Generates crates/quadra-text/src/nfc_table.rs: canonical compositions and combining
classes for the Latin blocks (Latin-1 through Latin Extended Additional, which covers every
Vietnamese letter). Run: python -I tools/gen_nfc.py"""
import os
import sys
import unicodedata

RANGES = [(0x00C0, 0x024F), (0x1E00, 0x1EFF)]


def collect():
    pairs, marks = [], {}
    for lo, hi in RANGES:
        for cp in range(lo, hi + 1):
            d = unicodedata.decomposition(chr(cp))
            if not d or d.startswith("<"):
                continue
            parts = [int(x, 16) for x in d.split()]
            if len(parts) != 2:
                continue
            if unicodedata.normalize("NFC", chr(parts[0]) + chr(parts[1])) != chr(cp):
                continue  # composition exclusions
            pairs.append((parts[0], parts[1], cp))
            marks[parts[1]] = unicodedata.combining(chr(parts[1]))
    for cp in list(range(0x0300, 0x0370)) + list(range(0x1DC0, 0x1E00)):
        c = unicodedata.combining(chr(cp))
        if c:
            marks[cp] = c
    return sorted(pairs), marks


def emit(f, doc, name, values, per_line):
    values = ["0x%04X" % v for v in values]
    f.write("\n/// %s\n#[rustfmt::skip]\npub(crate) static %s: [u16; %d] = [\n" % (doc, name, len(values)))
    for i in range(0, len(values), per_line):
        f.write("    " + ", ".join(values[i:i + per_line]) + ",\n")
    f.write("];\n")


def main():
    pairs, marks = collect()
    here = os.path.dirname(os.path.abspath(__file__))
    out = os.path.join(here, "..", "crates", "quadra-text", "src", "nfc_table.rs")
    with open(out, "w", encoding="utf-8", newline="\n") as f:
        f.write("//! Generated by tools/gen_nfc.py (Unicode %s). Do not edit.\n" % unicodedata.unidata_version)
        emit(f, "Canonical compositions as triples sorted by the first two: base, mark, composed.",
             "COMPOSED", (v for p in pairs for v in p), 15)
        apart = sorted((p[2], p[0], p[1]) for p in pairs)
        emit(f, "Canonical decompositions as triples sorted by the first: composed, base, mark.",
             "DECOMPOSED", (v for p in apart for v in p), 15)
        emit(f, "A combining mark and its canonical combining class, sorted by the mark.",
             "MARKS", (v for k in sorted(marks) for v in (k, marks[k])), 16)
    print("pairs:", len(pairs), "marks:", len(marks), "->", os.path.normpath(out))


main()
