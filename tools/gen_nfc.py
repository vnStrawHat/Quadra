"""Generate quadra/text/nfc_table.v: canonical compositions and combining classes
for the Latin blocks (Latin-1 through Latin Extended Additional, which covers
all Vietnamese letters). Run: python -I tools/gen_nfc.py"""
import os
import sys
import unicodedata

RANGES = [(0x00C0, 0x024F), (0x1E00, 0x1EFF)]


def collect():
    pairs, marks = [], {}
    for lo, hi in RANGES:
        for cp in range(lo, hi + 1):
            d = unicodedata.decomposition(chr(cp))
            if not d or d.startswith("<"):
                continue
            parts = [int(x, 16) for x in d.split()]
            if len(parts) != 2:
                continue
            if unicodedata.normalize("NFC", chr(parts[0]) + chr(parts[1])) != chr(cp):
                continue  # composition exclusions
            pairs.append((parts[0], parts[1], cp))
            marks[parts[1]] = unicodedata.combining(chr(parts[1]))
    for cp in list(range(0x0300, 0x0370)) + list(range(0x1DC0, 0x1E00)):
        c = unicodedata.combining(chr(cp))
        if c:
            marks[cp] = c
    return sorted(pairs), marks


def emit(f, name, values, per_line):
    """Emits hex values as a multi-line string, parsed once at startup (stays compact
    under v fmt)."""
    values = list(values)
    nl = chr(10)
    f.write("const %s = '%s" % (name, nl))
    for i in range(0, len(values), per_line):
        f.write(" ".join(values[i:i + per_line]) + nl)
    f.write("'" + nl)


def main():
    pairs, marks = collect()
    out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "quadra", "text", "nfc_table.v")
    with open(out, "w", encoding="utf-8", newline="\n") as f:
        f.write("// Generated by tools/gen_nfc.py (Python %d.%d, Unicode %s). Do not edit.\n"
                % (sys.version_info[0], sys.version_info[1], unicodedata.unidata_version))
        f.write("module text\n\n// Canonical compositions as flat triples: base, mark, composed.\n")
        emit(f, "nfc_pairs_src", ("%04X" % v for p in pairs for v in p), 24)
        f.write("\n// Canonical combining classes: mark, class.\n")
        emit(f, "nfc_marks_src", (x for k in sorted(marks) for x in ("%04X" % k, "%X" % marks[k])), 32)
    print("pairs:", len(pairs), "marks:", len(marks), "->", os.path.normpath(out))


main()
