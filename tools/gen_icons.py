"""Generate quadra/kit/icons.v from Lucide SVGs (ISC license).
Input: .cache/downloads/lucide/*.svg (data only, never executed).
Run: python -I tools/gen_icons.py"""
import os
import re

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
SRC = os.path.join(ROOT, ".cache", "downloads", "lucide")
OUT = os.path.join(ROOT, "quadra", "kit", "icons.v")
LICENSE_OUT = os.path.join(ROOT, "quadra", "kit", "LICENSE-lucide.txt")


def body(svg):
    svg = re.sub(r"<!--.*?-->", "", svg, flags=re.S)
    inner = re.search(r"<svg[^>]*>(.*)</svg>", svg, flags=re.S).group(1)
    inner = re.sub(r"\s+", " ", inner).strip()
    inner = re.sub(r"\s*/>", "/>", inner)
    return inner.replace("> <", "><").replace("'", "\\'")


def main():
    names = sorted(f[:-4] for f in os.listdir(SRC) if f.endswith(".svg"))
    nl = chr(10)
    with open(OUT, "w", encoding="utf-8", newline=nl) as f:
        f.write("// Generated by tools/gen_icons.py from Lucide 0.460.0 (ISC, see LICENSE-lucide.txt)." + nl)
        f.write("// Each constant is the body of a 24x24 stroked icon; kit.icon() wraps it." + nl)
        f.write("module kit" + nl + nl)
        for n in names:
            with open(os.path.join(SRC, n + ".svg"), encoding="utf-8") as s:
                f.write("pub const icon_%s = '%s'%s" % (n.replace("-", "_"), body(s.read()), nl))
    with open(os.path.join(SRC, "LICENSE"), encoding="utf-8") as s, open(LICENSE_OUT, "w", encoding="utf-8", newline=nl) as d:
        d.write(s.read())
    print(len(names), "icons ->", os.path.normpath(OUT))


main()
